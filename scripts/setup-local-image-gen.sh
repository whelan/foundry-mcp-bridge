#!/usr/bin/env bash
# One-time setup for LOCAL image generation on macOS (built for an Intel
# MacBook Pro 2019 — CPU only; Apple's Metal/MPS acceleration is Apple-Silicon
# only). Run this ONCE:
#
#   ./scripts/setup-local-image-gen.sh
#
# It installs Python (via Homebrew if needed), creates an isolated venv, installs
# a pinned diffusers/torch stack, downloads the sd-turbo model with a smoke-test
# render, and writes local-image-gen.env so scripts/make-image.sh can run.
#
# Flags:
#   --no-smoke   skip the test render (the model still downloads on first use)
#
# Re-running is safe (idempotent): it reuses the venv and only reinstalls if
# needed.
set -euo pipefail

SMOKE=1
for arg in "$@"; do
  case "$arg" in
    --no-smoke) SMOKE=0 ;;
    *) echo "setup: unknown flag '$arg'" >&2; exit 2 ;;
  esac
done

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENV="$REPO/.venv-image"
ENV_FILE="$REPO/local-image-gen.env"
PY_BIN="$VENV/bin/python"

say() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }

if [[ "$(uname)" != "Darwin" ]]; then
  echo "setup: this script targets macOS. On other platforms install Python 3 +" >&2
  echo "       scripts/image-gen-requirements.txt into a venv manually." >&2
  exit 1
fi

# 1. Python 3 (prefer an existing python3; otherwise install via Homebrew).
if ! command -v python3 >/dev/null 2>&1; then
  say "Python 3 not found — installing via Homebrew"
  if ! command -v brew >/dev/null 2>&1; then
    echo "setup: Homebrew is required to install Python. Install it from" >&2
    echo "       https://brew.sh and re-run this script." >&2
    exit 1
  fi
  brew install python
fi
say "Using $(python3 -V) at $(command -v python3)"

# 2. Node (needed by gen-image.mjs). The repo already requires it; just check.
if ! command -v node >/dev/null 2>&1; then
  echo "setup: Node.js is required (for scripts/gen-image.mjs). Install Node >=20" >&2
  echo "       (e.g. 'brew install node') and re-run." >&2
  exit 1
fi

# 3. Isolated venv + pinned deps.
if [[ ! -x "$PY_BIN" ]]; then
  say "Creating venv at $VENV"
  python3 -m venv "$VENV"
fi
say "Installing pinned image-gen dependencies (this can take a few minutes)"
"$PY_BIN" -m pip install --upgrade pip >/dev/null
"$PY_BIN" -m pip install -r "$REPO/scripts/image-gen-requirements.txt"

# 4. Write the env file consumed by make-image.sh / gen-image.mjs.
say "Writing $ENV_FILE"
cat > "$ENV_FILE" <<EOF
# Generated by scripts/setup-local-image-gen.sh — local image generation config.
# Consumed by scripts/make-image.sh (which sources it before gen-image.mjs).
IMAGE_GEN_BACKEND=cli
SD_MODEL=stabilityai/sd-turbo
IMAGE_GEN_CMD=$PY_BIN $REPO/scripts/sd_generate.py --prompt "{prompt}" --out "{out}" --width {width} --height {height} --steps {steps} --negative "{negative}"
EOF

# 5. Smoke test: downloads the model (~2.5 GB on first run) and renders once.
if [[ "$SMOKE" == "1" ]]; then
  say "Smoke test: downloading sd-turbo and rendering one image"
  mkdir -p "$REPO/generated-images"
  set -a; # shellcheck disable=SC1090
  source "$ENV_FILE"; set +a
  node "$REPO/scripts/gen-image.mjs" \
    --prompt "a friendly green dragon, fantasy portrait" \
    --out "$REPO/generated-images/smoke-test.png"
  say "Smoke test OK -> generated-images/smoke-test.png"
fi

cat <<EOF

Setup complete. Generate an image any time with:

  ./scripts/make-image.sh "a red dragon perched on a castle tower" dragon.png

Then have your local Foundry agent run the 'generate-and-upload-image' skill to
push it into the world (upload_asset + set it on an actor/scene/journal).
EOF
