#!/usr/bin/env bash
# GPU image generation on an Intel Mac with a discrete AMD Radeon Pro, via
# stable-diffusion.cpp built with Metal. This is the reliable way to use the GPU
# on an Intel Mac — PyTorch's MPS backend is unstable on Intel+AMD, whereas
# stable-diffusion.cpp drives the GPU through Metal compute (ggml).
#
# Run ONCE:
#   ./scripts/setup-sdcpp-metal.sh
#
# It installs build tools (Homebrew cmake/git), builds the `sd` binary with
# Metal, downloads an SD 1.5 fp16 checkpoint (~2 GB, fits a 4 GB GPU), writes
# local-image-gen.env to point at it, and smoke-renders one image. Afterwards
# generate with the SAME everyday command as the CPU path:
#
#   ./scripts/make-image.sh "a red dragon" dragon.png
#
# Flags:
#   --no-smoke   skip the test render
#
# Override the model with env vars before running:
#   SD_MODEL_URL=...  SD_MODEL_FILE=mymodel.safetensors  ./scripts/setup-sdcpp-metal.sh
#
# Caveat: ggml's Metal kernels are developed primarily for Apple-Silicon GPUs.
# They generally run on Intel-Mac AMD GPUs, but if you hit Metal errors, rebuild
# without Metal (set SD_NO_METAL=1) — sd.cpp's CPU path is still well optimized.
set -euo pipefail

SMOKE=1
for arg in "$@"; do
  case "$arg" in
    --no-smoke) SMOKE=0 ;;
    *) echo "setup: unknown flag '$arg'" >&2; exit 2 ;;
  esac
done

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SDCPP_DIR="$REPO/.sdcpp"
BUILD_DIR="$SDCPP_DIR/build"
BIN_DIR="$BUILD_DIR/bin"
SD_BIN=""   # resolved after the build (binary is sd-cli on newer sd.cpp, sd on older)
MODEL_DIR="$REPO/models"
ENV_FILE="$REPO/local-image-gen.env"

# CPU threads for sd.cpp (used by the CPU build). Defaults to ALL logical cores
# (hw.ncpu, e.g. 16). Override with SD_THREADS to pin a specific count.
THREADS="${SD_THREADS:-$(sysctl -n hw.ncpu)}"

# Default to DreamShaper 8 — an SD 1.5 finetune: same speed/RAM as base SD 1.5,
# but much nicer character portraits. Swap to vanilla SD 1.5 or another single-
# file checkpoint via SD_MODEL_URL / SD_MODEL_FILE.
SD_MODEL_URL="${SD_MODEL_URL:-https://huggingface.co/Lykon/DreamShaper/resolve/main/DreamShaper_8_pruned.safetensors}"
SD_MODEL_FILE="${SD_MODEL_FILE:-DreamShaper_8_pruned.safetensors}"
MODEL_PATH="$MODEL_DIR/$SD_MODEL_FILE"

say() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }

if [[ "$(uname)" != "Darwin" ]]; then
  echo "setup: this script targets macOS." >&2
  exit 1
fi

# 1. Xcode Command Line Tools (clang) — required to compile.
if ! xcode-select -p >/dev/null 2>&1; then
  say "Installing Xcode Command Line Tools (a GUI dialog will open)"
  xcode-select --install || true
  echo "Finish the Xcode CLT install, then re-run this script." >&2
  exit 1
fi

# 2. Build tools via Homebrew.
if ! command -v brew >/dev/null 2>&1; then
  echo "setup: Homebrew is required. Install it from https://brew.sh and re-run." >&2
  exit 1
fi
for tool in cmake git; do
  command -v "$tool" >/dev/null 2>&1 || { say "Installing $tool"; brew install "$tool"; }
done
command -v node >/dev/null 2>&1 || { echo "setup: Node >=20 required (brew install node)." >&2; exit 1; }

# 3. Clone (with the ggml submodule) and build with Metal.
if [[ ! -d "$SDCPP_DIR/.git" ]]; then
  say "Cloning stable-diffusion.cpp"
  git clone --recursive https://github.com/leejet/stable-diffusion.cpp "$SDCPP_DIR"
else
  say "Updating stable-diffusion.cpp"
  git -C "$SDCPP_DIR" pull --ff-only || true
  git -C "$SDCPP_DIR" submodule update --init --recursive
fi

METAL_FLAGS=(-DSD_METAL=ON -DGGML_METAL_EMBED_LIBRARY=ON)
if [[ "${SD_NO_METAL:-0}" == "1" ]]; then
  say "SD_NO_METAL=1 set — building CPU-only"
  # Pass -DSD_METAL=OFF explicitly: cmake caches SD_METAL=ON from a previous
  # Metal build, so merely omitting the flag would keep Metal enabled.
  METAL_FLAGS=(-DSD_METAL=OFF -DGGML_METAL=OFF)
fi
say "Configuring build${SD_NO_METAL:+ (CPU)}"
cmake -S "$SDCPP_DIR" -B "$BUILD_DIR" -DCMAKE_BUILD_TYPE=Release "${METAL_FLAGS[@]}"
say "Compiling (this can take a few minutes)"
cmake --build "$BUILD_DIR" --config Release -j"$(sysctl -n hw.ncpu)"
# Newer stable-diffusion.cpp names the CLI `sd-cli`; older builds produced `sd`.
for cand in "$BIN_DIR/sd-cli" "$BIN_DIR/sd"; do
  [[ -x "$cand" ]] && { SD_BIN="$cand"; break; }
done
[[ -n "$SD_BIN" ]] || { echo "setup: build produced no sd/sd-cli binary in $BIN_DIR" >&2; exit 1; }
say "Built CLI: $SD_BIN"

# 4. Model checkpoint.
mkdir -p "$MODEL_DIR"
if [[ ! -f "$MODEL_PATH" ]]; then
  say "Downloading model -> $MODEL_PATH (~2 GB)"
  curl -L -C - -o "$MODEL_PATH" "$SD_MODEL_URL"
else
  say "Model already present: $MODEL_PATH"
fi

# 5. Write the env consumed by make-image.sh / gen-image.mjs.
say "Writing $ENV_FILE"
cat > "$ENV_FILE" <<EOF
# Generated by scripts/setup-sdcpp-metal.sh — GPU (Metal) image generation.
# Consumed by scripts/make-image.sh (which sources it before gen-image.mjs).
IMAGE_GEN_BACKEND=cli
IMAGE_GEN_CMD='$SD_BIN -m $MODEL_PATH --threads $THREADS --seed -1 -p "{prompt}" -n "{negative}" -W {width} -H {height} --steps {steps} --cfg-scale 7 --sampling-method euler_a -o "{out}"'
EOF

# 6. Smoke test.
if [[ "$SMOKE" == "1" ]]; then
  say "Smoke test: rendering one image on the GPU"
  mkdir -p "$REPO/generated-images"
  set -a; # shellcheck disable=SC1090
  source "$ENV_FILE"; set +a
  node "$REPO/scripts/gen-image.mjs" \
    --prompt "a friendly green dragon, fantasy portrait" \
    --out "$REPO/generated-images/smoke-test.png" --steps 20
  say "Smoke test OK -> generated-images/smoke-test.png"
fi

cat <<EOF

Setup complete. Generate any time:

  ./scripts/make-image.sh "a red dragon perched on a castle tower" dragon.png \\
    --steps 25 --negative "ugly, deformed, blurry, low quality, bad anatomy, extra limbs, watermark, text"

DreamShaper 8 (SD 1.5) likes ~20-30 steps and benefits a lot from a negative
prompt. On this Mac use the CPU build (SD_NO_METAL=1) — Metal on the discrete AMD
GPU is slower than CPU and can white-image via the GPU watchdog.
EOF
