#!/usr/bin/env node
// Generate an image with a LOCAL AI backend, then hand it off for upload to
// Foundry. This is the "generate" half of the generate-and-upload-image skill;
// the "upload" half is the existing `upload_asset` MCP tool (the agent reads the
// base64 sidecar this writes and passes it along — see
// .claude/skills/generate-and-upload-image/SKILL.md).
//
// It deliberately does NOT talk to Foundry or the relay: in the live topology
// the MCP server owns the relay hub and the Foundry module is its sole client,
// so uploads must go through the `upload_asset` MCP tool, not a second relay
// connection. This script only produces a file + a base64 sidecar.
//
// Usage:
//   node scripts/gen-image.mjs --prompt "a red dragon portrait, dramatic light" \
//       (--out /tmp/dragon.png | --name dragon.png [--out-dir images]) \
//       [--backend cli|a1111|codex] [--width 768] [--height 768] \
//       [--steps 30] [--negative "blurry, text"] [--codex-model gpt-5.5] \
//       [--no-sidecar]
//
// Destination (pick one):
//   --out <path>   — exact output path, used verbatim.
//   --name <file>  — filename only; the directory comes from the first of
//                    --out-dir, IMAGE_GEN_OUT_DIR, "outputDir" in ./.imagegen.json,
//                    or "images/" under the cwd (created if missing).
//
// Backends (pick with --backend or IMAGE_GEN_BACKEND, default "cli"):
//   cli    — run a local CLI that writes the image file itself. Provide the
//            command template in IMAGE_GEN_CMD with placeholders {prompt} {out}
//            {width} {height} {steps} {negative}. Examples:
//              IMAGE_GEN_CMD='sd -p "{prompt}" -o "{out}" --steps {steps}'
//              IMAGE_GEN_CMD='python comfy_cli.py --prompt "{prompt}" --out "{out}"'
//   a1111  — POST to an Automatic1111 / SD-Forge WebUI HTTP API (it returns
//            base64 directly). Set SD_WEBUI_URL (default http://127.0.0.1:7860).
//   codex  — drive the OpenAI Codex CLI (`codex exec`, must be on PATH and
//            logged in) non-interactively; the image is generated by codex's
//            image tool, located in $CODEX_HOME/generated_images/<session>/ and
//            moved to the destination by this script (codex's sandbox cannot
//            write to the workspace). Model: --codex-model, "codex.model" in
//            .imagegen.json, or IMAGE_GEN_CODEX_MODEL. --width/--height become
//            a size hint in the prompt; --steps and --negative are
//            diffusion-specific and IGNORED by this backend. Timeout:
//            IMAGE_GEN_TIMEOUT_MS (default 300000).
//
// Output: writes the image to the destination, writes "<out>.b64" (raw base64,
// no newlines) unless --no-sidecar, and prints a one-line JSON summary to stdout
// (path, bytes, mimeType, b64Path) — never the base64 itself, to keep logs sane.

import { spawn } from "node:child_process";
import {
  readFile,
  writeFile,
  stat,
  readdir,
  mkdir,
  rename,
  copyFile,
  unlink,
} from "node:fs/promises";
import { basename, dirname, extname, join, resolve } from "node:path";
import { homedir } from "node:os";
import { pathToFileURL } from "node:url";

function parseArgs(argv) {
  const out = { sidecar: true };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--no-sidecar") { out.sidecar = false; continue; }
    if (!a.startsWith("--")) continue;
    const key = a.slice(2);
    const val = argv[i + 1];
    i++;
    out[key] = val;
  }
  return out;
}

function fail(msg) {
  console.error(`gen-image: ${msg}`);
  process.exit(1);
}

const MIME_BY_EXT = {
  ".png": "image/png",
  ".webp": "image/webp",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".svg": "image/svg+xml",
};

function mimeFor(path) {
  return MIME_BY_EXT[extname(path).toLowerCase()] ?? "application/octet-stream";
}

// Substitute {prompt} {out} {width} {height} {steps} {negative} into a template.
function fillTemplate(tpl, vars) {
  return tpl.replace(/\{(prompt|out|width|height|steps|negative)\}/g, (_, k) =>
    vars[k] ?? "",
  );
}

function runShell(cmd) {
  return new Promise((resolve, reject) => {
    // Use a shell so quoted placeholders in IMAGE_GEN_CMD behave as written.
    const child = spawn(cmd, { shell: true, stdio: ["ignore", "inherit", "inherit"] });
    child.on("error", reject);
    child.on("close", (code) =>
      code === 0 ? resolve() : reject(new Error(`backend exited with code ${code}`)),
    );
  });
}

async function backendCli(args) {
  const tpl = process.env.IMAGE_GEN_CMD;
  if (!tpl) {
    fail(
      "backend 'cli' needs IMAGE_GEN_CMD, e.g.\n" +
        `  IMAGE_GEN_CMD='sd -p "{prompt}" -o "{out}" --steps {steps}'`,
    );
  }
  const cmd = fillTemplate(tpl, {
    prompt: args.prompt.replace(/"/g, '\\"'),
    out: args.out,
    width: String(args.width ?? 512),
    height: String(args.height ?? 512),
    steps: String(args.steps ?? 30),
    negative: (args.negative ?? "").replace(/"/g, '\\"'),
  });
  console.error(`gen-image: running cli backend: ${cmd}`);
  await runShell(cmd);
  // The CLI is responsible for writing args.out; confirm it did.
  await stat(args.out).catch(() => fail(`backend did not produce ${args.out}`));
}

async function backendA1111(args) {
  const base = (process.env.SD_WEBUI_URL ?? "http://127.0.0.1:7860").replace(/\/$/, "");
  const body = {
    prompt: args.prompt,
    negative_prompt: args.negative ?? "",
    width: Number(args.width ?? 512),
    height: Number(args.height ?? 512),
    steps: Number(args.steps ?? 30),
  };
  console.error(`gen-image: POST ${base}/sdapi/v1/txt2img`);
  let res;
  try {
    res = await fetch(`${base}/sdapi/v1/txt2img`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify(body),
    });
  } catch (e) {
    fail(`cannot reach SD WebUI at ${base} (is it running with --api?): ${e.message}`);
  }
  if (!res.ok) fail(`SD WebUI returned ${res.status} ${res.statusText}`);
  const json = await res.json();
  const b64 = json?.images?.[0];
  if (!b64) fail("SD WebUI response had no images");
  // A1111 may prefix a data URL; strip it.
  const clean = b64.includes(",") ? b64.slice(b64.indexOf(",") + 1) : b64;
  await writeFile(args.out, Buffer.from(clean, "base64"));
}

// ---------------------------------------------------------------------------
// codex backend — pure helpers first (exported for tests), plumbing after.
// ---------------------------------------------------------------------------

// Wrap the user prompt so codex only generates: its sandbox cannot copy the
// file into the workspace (`unsupported call: exec_command`), so any attempt
// just wastes turns — this script moves the file itself afterwards.
export function buildCodexPrompt(args) {
  let prompt =
    "Use the image generation tool to generate exactly one image:\n\n" +
    `${args.prompt}\n\n` +
    "Do not attempt to save, copy, move, or verify the file — only generate it.";
  const width = args.width ?? args.height;
  const height = args.height ?? args.width;
  if (width && height) prompt += `\n\nTarget size: ${width}x${height}.`;
  return prompt;
}

// Find the codex session id in captured output: the first `thread.started`
// JSONL event's thread_id (with --json), falling back to the human banner's
// "session id: <uuid>" line. Non-JSON lines are tolerated.
export function parseCodexSessionId(lines) {
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed.startsWith("{")) continue;
    let event;
    try {
      event = JSON.parse(trimmed);
    } catch {
      continue;
    }
    if (event?.type === "thread.started" && typeof event.thread_id === "string") {
      return event.thread_id;
    }
  }
  const match = /session id:\s*([0-9a-f-]{36})/i.exec(lines.join("\n"));
  return match ? match[1] : null;
}

const CODEX_IMAGE_EXTS = new Set([".png", ".jpg", ".jpeg", ".webp"]);

// From a directory listing, pick the generated image: image extensions only,
// newest mtime wins; the rest are returned so the caller can warn about them.
export function pickGeneratedImage(entries) {
  const images = entries
    .filter((e) => CODEX_IMAGE_EXTS.has(extname(e.name).toLowerCase()))
    .sort((a, b) => b.mtimeMs - a.mtimeMs);
  return { chosen: images[0] ?? null, extras: images.slice(1) };
}

// Resolve the destination path: --out verbatim, else --name inside the
// project's output directory (--out-dir → IMAGE_GEN_OUT_DIR → .imagegen.json
// "outputDir" → "images/"). Returns null when neither --out nor --name given.
export function resolveOutPath(args, config, env, cwd) {
  if (args.out) return args.out;
  if (!args.name) return null;
  const dir =
    args["out-dir"] ?? env.IMAGE_GEN_OUT_DIR ?? config?.outputDir ?? "images";
  return resolve(cwd, dir, args.name);
}

// Read ./.imagegen.json (per-project knobs: outputDir, codex.model). Missing
// file → null; present but unparsable → warn and behave as if absent.
async function loadProjectConfig(cwd) {
  const path = join(cwd, ".imagegen.json");
  let text;
  try {
    text = await readFile(path, "utf8");
  } catch (e) {
    if (e?.code === "ENOENT") return null;
    throw e;
  }
  try {
    return JSON.parse(text);
  } catch (e) {
    console.error(`gen-image: ignoring invalid ${path}: ${e.message}`);
    return null;
  }
}

function outputTail(lines, n = 20) {
  return lines.slice(-n).join("\n");
}

// Move src to dest; rename() first, copy+unlink on EXDEV (codex's cache and
// the project typically live on different volumes).
async function moveFile(src, dest) {
  try {
    await rename(src, dest);
  } catch (e) {
    if (e?.code !== "EXDEV") throw e;
    await copyFile(src, dest);
    await unlink(src);
  }
}

// Run `codex <argv>`, capturing stdout as lines (stderr passes through for
// progress). Fails on missing binary, non-zero exit, or timeout.
function runCodex(argv, timeoutMs) {
  return new Promise((resolvePromise, reject) => {
    // stdin must be ignored: codex exec reads piped stdin and can hang on it.
    const child = spawn("codex", argv, { stdio: ["ignore", "pipe", "inherit"] });
    const lines = [];
    let buffer = "";
    let timedOut = false;
    const timer = setTimeout(() => {
      timedOut = true;
      child.kill("SIGKILL");
    }, timeoutMs);
    child.stdout.on("data", (chunk) => {
      buffer += chunk.toString("utf8");
      const parts = buffer.split("\n");
      buffer = parts.pop() ?? "";
      lines.push(...parts);
    });
    child.on("error", (e) => {
      clearTimeout(timer);
      if (e?.code === "ENOENT") {
        reject(
          new Error("backend 'codex' needs the OpenAI Codex CLI (`codex`) on PATH"),
        );
      } else {
        reject(e);
      }
    });
    child.on("close", (code) => {
      clearTimeout(timer);
      if (buffer) lines.push(buffer);
      if (timedOut) {
        reject(
          new Error(
            `codex exec timed out after ${timeoutMs}ms (IMAGE_GEN_TIMEOUT_MS to change)`,
          ),
        );
      } else if (code !== 0) {
        reject(
          new Error(
            `codex exec exited with code ${code} — last output:\n${outputTail(lines)}`,
          ),
        );
      } else {
        resolvePromise(lines);
      }
    });
  });
}

async function backendCodex(args, config) {
  const model =
    args["codex-model"] ?? config?.codex?.model ?? process.env.IMAGE_GEN_CODEX_MODEL;
  const timeoutMs = Number(process.env.IMAGE_GEN_TIMEOUT_MS ?? 300_000);
  if (!Number.isFinite(timeoutMs) || timeoutMs <= 0) {
    fail(
      `IMAGE_GEN_TIMEOUT_MS must be a positive number, got '${process.env.IMAGE_GEN_TIMEOUT_MS}'`,
    );
  }
  // -s read-only: codex must not write to the workspace at all; this script
  // does the move. --json: the first event carries the session/thread id.
  const argv = ["exec", "--json", "-s", "read-only", "--skip-git-repo-check"];
  if (model) argv.push("-m", model);
  argv.push(buildCodexPrompt(args));
  console.error(
    `gen-image: running codex exec${model ? ` (model ${model})` : ""}, timeout ${timeoutMs}ms`,
  );
  const lines = await runCodex(argv, timeoutMs);

  const sessionId = parseCodexSessionId(lines);
  if (!sessionId) {
    fail(
      "codex output had no session id (output format drift? this ran with --json) — " +
        `last output:\n${outputTail(lines)}`,
    );
  }
  const codexHome = process.env.CODEX_HOME ?? join(homedir(), ".codex");
  const sessionDir = join(codexHome, "generated_images", sessionId);
  let entries = [];
  try {
    const names = await readdir(sessionDir);
    entries = await Promise.all(
      names.map(async (name) => ({
        name,
        mtimeMs: (await stat(join(sessionDir, name))).mtimeMs,
      })),
    );
  } catch {
    // Missing dir is handled below as "no image".
  }
  const { chosen, extras } = pickGeneratedImage(entries);
  if (!chosen) {
    fail(
      `codex completed but produced no image in ${sessionDir} ` +
        `(the model may have answered in text or refused) — last output:\n${outputTail(lines)}`,
    );
  }
  if (extras.length > 0) {
    console.error(
      `gen-image: codex produced ${extras.length + 1} images; using newest ` +
        `${chosen.name}, ignoring ${extras.map((e) => e.name).join(", ")}`,
    );
  }
  await mkdir(dirname(args.out), { recursive: true });
  await moveFile(join(sessionDir, chosen.name), args.out);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.prompt) fail("missing --prompt");
  if (args.name && (args.name !== basename(args.name) || args.name === "..")) {
    fail(`--name must be a bare filename, got '${args.name}'`);
  }
  const cwd = process.cwd();
  const config = await loadProjectConfig(cwd);
  const out = resolveOutPath(args, config, process.env, cwd);
  if (!out) fail("missing --out or --name");
  args.out = out;
  await mkdir(dirname(resolve(cwd, out)), { recursive: true });
  const backend = args.backend ?? process.env.IMAGE_GEN_BACKEND ?? "cli";

  if (backend === "cli") await backendCli(args);
  else if (backend === "a1111") await backendA1111(args);
  else if (backend === "codex") await backendCodex(args, config);
  else fail(`unknown backend '${backend}' (expected cli | a1111 | codex)`);

  const bytes = await readFile(args.out);
  const summary = {
    path: args.out,
    name: basename(args.out),
    bytes: bytes.length,
    mimeType: mimeFor(args.out),
    b64Path: null,
  };
  if (args.sidecar) {
    const b64Path = `${args.out}.b64`;
    await writeFile(b64Path, bytes.toString("base64"));
    summary.b64Path = b64Path;
  }
  console.log(JSON.stringify(summary));
}

